def main():
    total_files = 0
    total_lines = 0
    for sector in SECTORS:
        if sector not in META:
            print(f"⚠ Skipping {sector}: no metadata")
            continue
        meta = META[sector]
        sector_dir = os.path.join(BASE, sector)
        os.makedirs(sector_dir, exist_ok=True)
        sector_files = 0
        sector_lines = 0
        for idx, phase in enumerate(PHASES):
            phase_dir = os.path.join(sector_dir, phase)
            os.makedirs(phase_dir, exist_ok=True)
            content = gen_content(sector, meta, idx)
            filepath = os.path.join(phase_dir, f"{phase}.md")
            with open(filepath, "w", encoding="utf-8") as f:
                f.write(content)
                f.write("\n")
            file_lines = content.count("\n") + 1
            total_files += 1
            total_lines += file_lines
            sector_files += 1
            sector_lines += file_lines
        print(f"  ✓ {sector}: {sector_files} files, {sector_lines} lines")
    print(f"\n{'='*60}")
    print(f"Total: {total_files} files, {total_lines} lines")
    print(f"{'='*60}")


if __name__ == "__main__":
    main()
